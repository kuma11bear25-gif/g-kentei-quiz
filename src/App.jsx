/* ---------------- クイズ画面 ---------------- */
function QuizView({ chapter, qIdx, total, question, selected, revealed, onPick, onNext, onExit, currentScore, qStat }) {
  const pct = ((qIdx + (revealed ? 1 : 0)) / total) * 100;
  const status = classifyStat(qStat);

  // 出題のたびに選択肢の並び順をシャッフルする（元の配列上のインデックスは保持し、
  // 正誤判定や正解回数の記録には常に元のインデックスを使う）
  const shuffledOptions = useMemo(() => {
    const withIdx = question.options.map((text, origIdx) => ({ text, origIdx }));
    for (let i = withIdx.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [withIdx[i], withIdx[j]] = [withIdx[j], withIdx[i]];
    }
    return withIdx;
  }, [question]);

  return (
    <div>
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: 10 }}>
        <button
          onClick={onExit}
          style={{ background: "none", border: "none", color: navy, fontSize: 13, padding: 0 }}
        >
          ← 章選択に戻る
        </button>
        <div style={{ fontSize: 13, color: "#6B7280" }}>
          第{chapter.no}章・{qIdx + 1} / {total} 問
        </div>
      </div>

      <div style={{ height: 6, background: "#E7E4D8", borderRadius: 3, overflow: "hidden", marginBottom: 20 }}>
        <div
          style={{
            height: "100%",
            width: `${pct}%`,
            background: gold,
            transition: "width 0.3s ease",
          }}
        />
      </div>

      <Ticket style={{ padding: 20, marginBottom: 16 }}>
        <div
          style={{
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
            marginBottom: 8,
          }}
        >
          <div style={{ fontFamily: serif, fontSize: 12, color: navy, letterSpacing: 1 }}>{chapter.title}</div>
          <div
            style={{
              fontSize: 11,
              fontWeight: 700,
              color: STATUS_COLOR[status],
              background: STATUS_BG[status],
              border: `1px solid ${STATUS_COLOR[status]}`,
              borderRadius: 20,
              padding: "2px 9px",
              whiteSpace: "nowrap",
            }}
          >
            {STATUS_LABEL[status]}
          </div>
        </div>
        <p style={{ fontSize: 17, lineHeight: 1.7, margin: 0, fontWeight: 600 }}>{question.q}</p>
      </Ticket>

      <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
        {shuffledOptions.map(({ text: opt, origIdx: i }, displayIdx) => {
          const isCorrect = i === question.correct;
          const isChosen = i === selected;
          let bg = "#FFFFFF";
          let border = line;
          let textColor = ink;
          if (revealed) {
            if (isCorrect) {
              bg = "#F5EFDE";
              border = gold;
            } else if (isChosen && !isCorrect) {
              bg = "#F7EAEA";
              border = brick;
              textColor = brick;
            }
          }
          return (
            <button
              key={i}
              disabled={revealed}
              onClick={() => onPick(i)}
              style={{
                display: "flex",
                alignItems: "center",
                gap: 12,
                textAlign: "left",
                padding: "14px 16px",
                background: bg,
                border: `1.5px solid ${border}`,
                borderRadius: 4,
                color: textColor,
                fontSize: 15,
                lineHeight: 1.5,
                opacity: revealed && !isCorrect && !isChosen ? 0.55 : 1,
              }}
            >
              <span
                style={{
                  width: 26,
                  height: 26,
                  borderRadius: "50%",
                  border: `1.5px solid ${revealed && (isCorrect || isChosen) ? border : "#B9B4A5"}`,
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  fontSize: 12,
                  flexShrink: 0,
                  fontWeight: 700,
                  color: revealed && isCorrect ? gold : revealed && isChosen ? brick : "#8A8F98",
                }}
              >
                {String.fromCharCode(65 + displayIdx)}
              </span>
              <span style={{ flex: 1 }}>{opt}</span>
              {revealed && isCorrect && <span style={{ fontSize: 13, fontWeight: 700, color: gold }}>正解</span>}
              {revealed && isChosen && !isCorrect && (
                <span style={{ fontSize: 13, fontWeight: 700, color: brick }}>選択</span>
              )}
            </button>
          );
        })}
      </div>

      {revealed && (
        <div
          style={{
            marginTop: 16,
            padding: 16,
            background: "#EFF2EE",
            borderLeft: `4px solid ${navy}`,
            borderRadius: 3,
            fontSize: 14,
            lineHeight: 1.7,
          }}
        >
          <div style={{ fontWeight: 700, color: navy, marginBottom: 6, fontSize: 13 }}>解説</div>
          {question.exp}
        </div>
      )}

      {revealed && (
        <button
          onClick={onNext}
          style={{
            marginTop: 18,
            width: "100%",
            padding: "14px 0",
            background: navyDeep,
            color: "#F5F4EF",
            border: "none",
            borderRadius: 4,
            fontSize: 15,
            fontWeight: 700,
            letterSpacing: 1,
          }}
        >
          {qIdx + 1 < total ? "次の問題へ" : "結果を見る"}
        </button>
      )}
    </div>
  );
}

