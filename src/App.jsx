/* ============================================================
   localStorage ベースの簡易ストレージ層
   （Claude.aiアーティファクト専用の window.storage API の代わりに、
    通常のブラウザ環境で動く localStorage を同じ非同期インターフェースでラップ）
   ============================================================ */
const LS_PREFIX = "gkentei:";

window.storage = {
  async get(key) {
    const raw = localStorage.getItem(LS_PREFIX + key);
    if (raw === null) return null;
    return { key, value: raw, shared: false };
  },
  async set(key, value) {
    localStorage.setItem(LS_PREFIX + key, value);
    return { key, value, shared: false };
  },
  async delete(key) {
    const existed = localStorage.getItem(LS_PREFIX + key) !== null;
    localStorage.removeItem(LS_PREFIX + key);
    return { key, deleted: existed, shared: false };
  },
  async list(prefix = "") {
    const keys = [];
    for (let i = 0; i < localStorage.length; i++) {
      const k = localStorage.key(i);
      if (k && k.startsWith(LS_PREFIX + prefix)) {
        keys.push(k.slice(LS_PREFIX.length));
      }
    }
    return { keys, prefix, shared: false };
  },
};

