export default function GKenteiQuiz() {
  const [view, setView] = useState("chapters"); // chapters | quiz | result
  const [chapterIdx, setChapterIdx] = useState(0);
  const [qIdx, setQIdx] = useState(0);
  const [selected, setSelected] = useState(null);
  const [revealed, setRevealed] = useState(false);
  const [answers, setAnswers] = useState([]); // {correct:boolean}
  const [progress, setProgress] = useState({}); // chapterId -> {best, attempts}
  const [loaded, setLoaded] = useState(false);
  const [qStats, setQStats] = useState({}); // 現在の章: 問題index -> {c: 正解回数, a: 挑戦回数}
  const [sessionIndices, setSessionIndices] = useState([]); // 今回出題する問題の元配列インデックス（ランダム10問）
  const [savedSessions, setSavedSessions] = useState({}); // chapterId -> 途中保存されたクイズの状態

  const chapter = CHAPTERS[chapterIdx];
  const currentOriginalIdx = sessionIndices[qIdx];
  const question = chapter && currentOriginalIdx !== undefined ? chapter.questions[currentOriginalIdx] : null;

  // load progress ＆ 途中保存されたクイズの状態
  useEffect(() => {
    (async () => {
      const [progressMap, sessionMap] = await Promise.all([
        loadStorageMap("progress:"),
        loadStorageMap("session:"),
      ]);
      setProgress(progressMap);
      setSavedSessions(sessionMap);
      setLoaded(true);
    })();
  }, []);

  // クイズ回答中の状態を都度保存し、途中で離脱しても再開できるようにする
  useEffect(() => {
    if (view !== "quiz" || !chapter || sessionIndices.length === 0) return;
    const snapshot = { sessionIndices, qIdx, answers, selected, revealed };
    window.storage.set(`session:${chapter.id}`, JSON.stringify(snapshot)).catch(() => {});
    setSavedSessions((prev) => ({ ...prev, [chapter.id]: snapshot }));
  }, [view, chapter, sessionIndices, qIdx, answers, selected, revealed]);

  const saveProgress = useCallback(async (chapterId, scoreVal, total) => {
    try {
      const key = `progress:${chapterId}`;
      let prev = null;
      try {
        const r = await window.storage.get(key);
        if (r && r.value) prev = JSON.parse(r.value);
      } catch (e) {}
      const attempts = (prev?.attempts || 0) + 1;
      const best = Math.max(prev?.best || 0, scoreVal);
      const next = { best, last: scoreVal, total, attempts };
      await window.storage.set(key, JSON.stringify(next));
      setProgress((p) => ({ ...p, [chapterId]: next }));
    } catch (e) {
      // storage unavailable — ignore silently
    }
  }, []);

  const loadQStats = useCallback(async (chapterId) => {
    try {
      const r = await window.storage.get(`qstats:${chapterId}`);
      return r && r.value ? JSON.parse(r.value) : {};
    } catch (e) {
      return {};
    }
  }, []);

  async function startChapter(idx) {
    const ch = CHAPTERS[idx];
    const stats = await loadQStats(ch.id);
    const saved = savedSessions[ch.id];
    if (saved && saved.sessionIndices?.length) {
      // 途中保存されたクイズがあれば、続きから再開する
      setSessionIndices(saved.sessionIndices);
      setChapterIdx(idx);
      setQIdx(saved.qIdx);
      setSelected(saved.selected ?? null);
      setRevealed(!!saved.revealed);
      setAnswers(saved.answers || []);
      setQStats(stats);
      setView("quiz");
      return;
    }
    // 3回以上正解した問題（習得済み）は出題対象から除外し、
    // 残った問題は正解回数が少ないほど重みを大きくして、ランダムだが優先的に出題されるようにする
    const candidates = ch.questions
      .map((_, i) => i)
      .filter((i) => (stats[i]?.c || 0) < 3);
    const pool = candidates.length > 0 ? candidates : ch.questions.map((_, i) => i);
    const weights = pool.map((i) => 1 / ((stats[i]?.c || 0) + 1));
    const picked = weightedSampleIndices(weights, Math.min(10, pool.length)).map((wi) => pool[wi]);
    setSessionIndices(picked);
    setChapterIdx(idx);
    setQIdx(0);
    setSelected(null);
    setRevealed(false);
    setAnswers([]);
    setQStats(stats);
    setView("quiz");
  }

  async function browseChapter(idx) {
    const ch = CHAPTERS[idx];
    const stats = await loadQStats(ch.id);
    setChapterIdx(idx);
    setQStats(stats);
    setView("browse");
  }

  // 正解履歴（章内の問題インデックス -> {c: 正解回数, a: 挑戦回数}）を1キーにまとめて保存
  function recordAnswer(idx, isCorrect) {
    setQStats((prev) => {
      const cur = prev[idx] || { c: 0, a: 0 };
      const next = { ...prev, [idx]: { c: cur.c + (isCorrect ? 1 : 0), a: cur.a + 1 } };
      window.storage.set(`qstats:${chapter.id}`, JSON.stringify(next)).catch(() => {});
      return next;
    });
  }

  function pickOption(i) {
    if (revealed) return;
    const isCorrect = i === question.correct;
    setSelected(i);
    setRevealed(true);
    setAnswers((a) => [...a, { correct: isCorrect }]);
    recordAnswer(currentOriginalIdx, isCorrect);
  }

  function nextQuestion() {
    if (qIdx + 1 < sessionIndices.length) {
      setQIdx(qIdx + 1);
      setSelected(null);
      setRevealed(false);
    } else {
      const finalScore = answers.filter((a) => a.correct).length;
      saveProgress(chapter.id, finalScore, sessionIndices.length);
      // 章を完走したので途中保存は不要になる
      window.storage.delete(`session:${chapter.id}`).catch(() => {});
      setSavedSessions((prev) => {
        const next = { ...prev };
        delete next[chapter.id];
        return next;
      });
      setView("result");
    }
  }

  const score = answers.filter((a) => a.correct).length;

  return (
    <div
      style={{
        minHeight: "100vh",
        background: paper,
        color: ink,
        fontFamily: sans,
        paddingBottom: 40,
      }}
    >
      <style>{`
        * { box-sizing: border-box; }
        button { font-family: inherit; cursor: pointer; }
        button:focus-visible, [tabindex]:focus-visible { outline: 2px solid ${navy}; outline-offset: 2px; }
        @media (prefers-reduced-motion: reduce) { * { transition: none !important; animation: none !important; } }
      `}</style>

      {/* ヘッダー */}
      <header
        style={{
          background: navyDeep,
          color: "#F1EFE6",
          padding: "22px 20px 26px",
          borderBottom: `3px solid ${gold}`,
        }}
      >
        <div style={{ maxWidth: 640, margin: "0 auto" }}>
          <div style={{ fontSize: 11, letterSpacing: 3, opacity: 0.7, marginBottom: 6 }}>
            JDLA SYLLABUS 2024 ／ 全8章対応
          </div>
          <h1 style={{ fontFamily: serif, fontSize: 26, margin: 0, fontWeight: 700, letterSpacing: 1 }}>
            G検定 問題集
          </h1>
        </div>
      </header>

      <main style={{ maxWidth: 640, margin: "0 auto", padding: "20px 16px" }}>
        {view === "chapters" && (
          <ChapterList
            chapters={CHAPTERS}
            progress={progress}
            savedSessions={savedSessions}
            loaded={loaded}
            onSelect={startChapter}
            onBrowse={browseChapter}
          />
        )}

        {view === "browse" && chapter && (
          <QuestionBrowseView chapter={chapter} qStats={qStats} onExit={() => setView("chapters")} />
        )}

        {view === "quiz" && question && (
          <QuizView
            chapter={chapter}
            qIdx={qIdx}
            total={sessionIndices.length}
            question={question}
            selected={selected}
            revealed={revealed}
            onPick={pickOption}
            onNext={nextQuestion}
            onExit={() => setView("chapters")}
            currentScore={score}
            qStat={qStats[currentOriginalIdx]}
          />
        )}

        {view === "result" && (
          <ResultView
            chapter={chapter}
            sessionQuestions={sessionIndices.map((i) => chapter.questions[i])}
            answers={answers}
            onRetry={() => startChapter(chapterIdx)}
            onHome={() => setView("chapters")}
          />
        )}
      </main>
    </div>
  );
}

